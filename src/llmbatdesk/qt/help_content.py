FAQ = """常见问题

为什么脚本“完全解析”却不能启动？
解析描述脚本写了什么；可运行性描述这些路径和命令在当前电脑是否存在。两者彼此独立。

为什么复制来的 BAT 显示模型或程序不存在？
脚本中的绝对路径仍指向原电脑。LLMBatDesk 会保留并展示这些值，但不会猜测或替换路径。

为什么“活动服务”是空的？
只有通过 PID、创建时间、命令行、进程树和端口归属验证的实时服务才会显示。
数据库旧记录或短暂存在的 cmd.exe 都不足以证明模型服务器在运行。

临时端口会修改原脚本吗？
不会。符合安全条件时只在 %LOCALAPPDATA%\\LLMBatDesk 下生成临时副本，
并验证除目标端口字面量外没有无关变化。

为什么某些脚本不能临时改端口？
set /p、分支、外部 CALL、运行时计算、未解析的延迟扩展或生成脚本无法安全静态定位。

为什么勾选“不再询问”后仍可能出现确认？
信任只覆盖当前内容哈希和工作目录。真实交互输入、动态解析、临时端口、端口冲突或其他
安全警告仍必须确认，窗口会明确列出原因。服务器命令后的尾部 pause 不属于真实输入；
可信且未变化后不会反复确认。启动前 pause、set /p 和 choice 仍属于交互。

“外部编辑器”应该填写什么？
不需要填写命令。选择 Windows 默认关联，或点击“浏览……”选择 Notepad、Notepad++、
VS Code 等编辑器 EXE。它只影响“打开脚本”。

怎样调整运行日志字体？
在“设置 → 日志”选择字体、字号和行距；Ctrl+滚轮可临时缩放，Ctrl+0 恢复配置字号。
这些设置不会改变主界面字体。

为什么“状态”和“API”显示不同？
它们是独立状态轴。“运行中”表示进程归属有效，“API 未就绪”可能表示仍在加载。
成功后会显示“运行中 / API 已就绪”，不会在两列重复 API 文本。

便携版为什么启动较慢？
OneFile 便携版需要先把只读运行时文件解压到临时目录。配置、数据库、日志、
元数据和临时启动脚本仍保存在 %LOCALAPPDATA%\\LLMBatDesk。

为什么删除便携版 EXE 后设置和日志还在？
便携版只表示程序是单个 EXE，不表示用户数据跟随 EXE。为避免升级或移动程序时丢失数据，
LLMBatDesk 始终使用 LocalAppData。可在“设置 → 存储与清理”中查看或删除全部数据。

“端口监听中，API 未就绪”是不是启动失败？
不一定。它表示端口已经由已验证服务器占用，但 API 还在加载、需要认证、端点不兼容或请求
超时。查看运行详情中的 URL、HTTP 状态和最后错误，或使用“重新检查 API”。

为什么会出现控制台窗口？
只有选择“显示原始控制台窗口”或设置脚本级覆盖时才会显示。默认后台模式使用 Windows
无窗口启动标志并捕获日志。交互脚本在后台可能等待看不见的输入，因此会强制警告。

日志中的网址和颜色有什么作用？
颜色按常见严重程度分类，网址可用系统默认处理程序打开。暂停画面不会停止磁盘捕获，
清空显示也不会删除日志文件。

模型库会影响正在运行的模型吗？
默认不会。模型库不代理推理、不查询推理流量，也没有周期扫描或文件监视器。模型服务处于
启动、运行、停止或可能分离运行时，手动扫描默认被阻止；扫描结束后也不会保留工作线程。

为什么启用模型库后没有自动出现模型？
这是预期行为。模型库只扫描用户明确添加的目录，而且扫描必须手动开始。未变化文件按路径、
大小和修改时间使用缓存，不会重新打开；完整 GGUF 哈希不会自动计算。

为什么添加目录后只出现目录，没有立即出现模型？
添加目录和扫描是两个明确操作。添加成功会立即显示目录；为了避免意外磁盘负载，仍需点击
“扫描所选目录”或“扫描全部目录”。重复添加会选中原目录并给出提示。

为什么一个脚本会显示多个模型引用？
主模型、mmproj 多模态投影、草稿模型和适配器是不同角色，不表示多个主模型冲突。只有现有
解析结果发现两个不同的主模型参数时才标为歧义；动态路径不会猜测关联。

为什么升级后仍显示旧的 GGUF 读取错误？
升级不会自动扫描。下一次明确手动扫描会识别旧读取器版本并重读，同时保留标签、备注和
引用。成功后旧错误立即清除；当前版本已确认的损坏文件不会在每次目录扫描反复读取。

为什么默认表格没有显示 mmproj、MTP 或 LoRA？
这些是附属组件，不应作为普通主模型占据默认列表。勾选“显示附属 GGUF”可以查看全部；
选择主模型时，“关联组件”仍会显示由脚本明确引用的组件。

为什么“关联组件”有时不显示表格？
没有经脚本确认的组件时会显示紧凑的“无关联组件”，避免空表占用空间。选择 mmproj、
草稿或适配器时，标题会改为“关联主模型”，同一组件可列出多个主模型和脚本。

“重新扫描脚本库”会只处理当前脚本吗？
不会。它是全局操作，会重新扫描所有已配置脚本根和单独添加的脚本，因此放在脚本库顶部。
选中脚本的启动、停止、打开等操作仍留在底部动作栏。

“移除脚本”会永久删除 BAT/CMD 吗？
默认不会。单独添加的脚本只取消注册；目录发现的脚本只保存精确路径忽略记录。只有明确选择
并第二次确认后才调用 Windows 回收站。回收站失败时原文件和脚本库数据保持不变，不会改用
永久删除。历史启动记录和日志会保留。

怎样恢复被忽略的目录脚本？
打开“文件 → 管理已忽略脚本”，选择记录并点击“取消忽略”。这不会执行脚本；随后只通过
普通脚本库扫描恢复显示。管理窗口也能按用户请求清理已经不存在的精确路径记录。

“疑似重复”是否表示两个文件完全相同？
不是。它只基于大小、规范化名称、架构、参数数量和量化元数据作启发式提示，没有读取完整
文件计算哈希，因此不能作为精确重复结论。
"""


