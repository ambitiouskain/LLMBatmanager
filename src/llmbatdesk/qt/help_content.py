FAQ = """常见问题

为什么脚本“完全解析”却不能启动？
解析描述脚本写了什么；可运行性描述这些路径和命令在当前电脑是否存在。两者彼此独立。

为什么复制来的 BAT 显示模型或程序不存在？
脚本中的绝对路径仍指向原电脑。LLMBatDesk 会保留并展示这些值，但不会猜测或替换路径。

为什么“活动服务”是空的？
只有通过 PID、创建时间、命令行、进程树和端口归属验证的实时服务才会显示。
数据库旧记录或短暂存在的 cmd.exe 都不足以证明模型服务器在运行。

临时端口会修改原脚本吗？
不会。符合安全条件时只在 %LOCALAPPDATA%\\LLMBatDesk 下生成临时副本，
并验证除目标端口字面量外没有无关变化。

为什么某些脚本不能临时改端口？
set /p、分支、外部 CALL、运行时计算、未解析的延迟扩展或生成脚本无法安全静态定位。

为什么勾选“不再询问”后仍可能出现确认？
信任只覆盖当前内容哈希和工作目录。真实交互输入、动态解析、临时端口、端口冲突或其他
安全警告仍必须确认，窗口会明确列出原因。服务器命令后的尾部 pause 不属于真实输入；
可信且未变化后不会反复确认。启动前 pause、set /p 和 choice 仍属于交互。

“外部编辑器”应该填写什么？
不需要填写命令。选择 Windows 默认关联，或点击“浏览……”选择 Notepad、Notepad++、
VS Code 等编辑器 EXE。它只影响“打开脚本”。

怎样调整运行日志字体？
在“设置 → 日志”选择字体、字号和行距；Ctrl+滚轮可临时缩放，Ctrl+0 恢复配置字号。
这些设置不会改变主界面字体。

为什么“状态”和“API”显示不同？
它们是独立状态轴。“运行中”表示进程归属有效，“API 未就绪”可能表示仍在加载。
成功后会显示“运行中 / API 已就绪”，不会在两列重复 API 文本。

便携版为什么启动较慢？
OneFile 便携版需要先把只读运行时文件解压到临时目录。配置、数据库、日志、
元数据和临时启动脚本仍保存在 %LOCALAPPDATA%\\LLMBatDesk。

为什么删除便携版 EXE 后设置和日志还在？
便携版只表示程序是单个 EXE，不表示用户数据跟随 EXE。为避免升级或移动程序时丢失数据，
LLMBatDesk 始终使用 LocalAppData。可在“设置 → 存储与清理”中查看或删除全部数据。

“端口监听中，API 未就绪”是不是启动失败？
不一定。它表示端口已经由已验证服务器占用，但 API 还在加载、需要认证、端点不兼容或请求
超时。查看运行详情中的 URL、HTTP 状态和最后错误，或使用“重新检查 API”。

为什么会出现控制台窗口？
只有选择“显示原始控制台窗口”或设置脚本级覆盖时才会显示。默认后台模式使用 Windows
无窗口启动标志并捕获日志。交互脚本在后台可能等待看不见的输入，因此会强制警告。

日志中的网址和颜色有什么作用？
颜色按常见严重程度分类，网址可用系统默认处理程序打开。暂停画面不会停止磁盘捕获，
清空显示也不会删除日志文件。
"""


